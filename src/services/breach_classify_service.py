# Step 2 — BreachClassify.
#
# Design Decision Record (docs/02_design.md): severity tier and credit
# eligibility directly determine remediation urgency and the SLA credit
# claim basis — a legally/financially significant decision. Per
# IMPLEMENTATION_LOG.md A4, decisions with legal/financial consequence must
# be deterministic (no `llm` parameter in the signature); LLM is used only
# to generate a non-authoritative rationale sentence in
# build_classification_rationale(), never to decide severity/eligibility
# itself.
#
# Threshold provenance (per an earlier prior design review — applied
# proactively here from the start): severity_thresholds and
# credit_eligible_tiers are institution-configurable via config.yaml
# (proposal §10/§12: "embeddable directly from published standards").
# ITIL4/ISO 20000 do not themselves publish one universal numeric deviation
# threshold — the defaults shipped in config.yaml are ILLUSTRATIVE, not
# extracted from a cited section of either standard. See
# docs/07_operation_guide.md "Severity Threshold Setup" for the required
# institution calibration step before production use.

from __future__ import annotations

from typing import Any

from src.services.breach_event_ingest_service import contains_disallowed_content

VALID_SEVERITY_TIERS = ("critical", "major", "minor")

DEFAULT_SEVERITY_THRESHOLDS = {"critical": 0.20, "major": 0.05}
DEFAULT_CREDIT_ELIGIBLE_TIERS = ("critical", "major")


def compute_breach_ratio(threshold: float, actual_value: float) -> float:
    """Deterministic deviation ratio between the actual value and the SLA
    threshold. Falls back to the absolute actual value when threshold is 0
    to avoid a division error (a 0 threshold is itself a degenerate SLA
    target, e.g. 'zero tolerance' metrics)."""
    if threshold == 0:
        return abs(actual_value)
    return abs(actual_value - threshold) / abs(threshold)


def classify_severity(threshold: float, actual_value: float, severity_thresholds: dict[str, float]) -> str:
    """Deterministic severity classification. Returns one of
    VALID_SEVERITY_TIERS. No `llm` parameter — this signature is asserted by
    a PB test (A4 principle)."""
    breach_ratio = compute_breach_ratio(threshold, actual_value)
    if breach_ratio >= severity_thresholds["critical"]:
        return "critical"
    if breach_ratio >= severity_thresholds["major"]:
        return "major"
    return "minor"


def is_credit_eligible(severity_tier: str, credit_eligible_tiers: Any) -> bool:
    """Deterministic credit-eligibility check. No `llm` parameter."""
    return severity_tier in credit_eligible_tiers


def _credit_eligibility_clause(credit_eligible: bool, severity_policy_verified: bool) -> str:
    # prior design review M2 (round 2): the classification rationale is inserted
    # verbatim into the released report (report_assemble_service.py's
    # "Classification Rationale" field) — it must therefore obey the same
    # severity_policy_verified gate as the Executive Summary/Breach
    # Detail/Remediation Plan surfaces, not just state a raw boolean.
    if not severity_policy_verified:
        return "credit eligibility requires contract-manager determination"
    return "credit-eligible" if credit_eligible else "not credit-eligible"


def build_classification_rationale(
    severity_tier: str, credit_eligible: bool, severity_policy_verified: bool, llm: Any = None
) -> str:
    """Narrative-only rationale sentence. Never changes severity_tier/
    credit_eligible — those are already decided deterministically before
    this is called.

    The credit-eligibility clause is ALWAYS the deterministic
    `_credit_eligibility_clause()` result — appended after the LLM-drafted
    severity narrative when an `llm` is configured, never generated by (or
    delegated to) the LLM itself, so an LLM cannot bypass the
    severity_policy_verified gate by asserting eligibility on its own
    (mirrors remediation_draft_service.py's pattern).

    Fail-safe: applies the same prohibited-content discard filter as the
    other LLM-generated sections — this text is inserted verbatim into the
    released report by report_assemble_service, so it must not be exempt
    from the "no employee name/monetary value in output" guarantee.
    """
    credit_clause = _credit_eligibility_clause(credit_eligible, severity_policy_verified)
    fallback = f"Classified as '{severity_tier}' severity ({credit_clause}) based on the configured SLA breach-ratio thresholds."
    if llm is None:
        return fallback
    prompt = (
        f"In one sentence, explain why an SLA breach was classified as "
        f"'{severity_tier}' severity. Do not restate a different severity tier. "
        "Do not make any statement about credit eligibility — that is appended "
        "separately by this system, not by you. Do not mention any employee "
        "name or monetary amount."
    )
    try:
        response = llm.complete([{"role": "user", "content": prompt}])
        text = response.get("content", "") if isinstance(response, dict) else str(response)
    except Exception:
        return fallback

    if not text or contains_disallowed_content(text):
        return fallback
    return f"{text} ({credit_clause})."
