# Step 7 — OutputValidate. S-3: belt-and-suspenders re-scan of the assembled
# report for prohibited content, independent of any upstream check (defense
# in depth — mirrors IMPLEMENTATION_LOG.md B5's SecurityGateOutputNode
# pattern). Reuses the same name/money/Japanese-script detectors as step 1
# so there is exactly one prohibited-content-shape definition to maintain.
# Deliberately does NOT check for PLATFORM_MASK_TOKEN here — "[MASKED]"
# appearing in the assembled report is the safe, already-redacted state,
# not a leak.

from __future__ import annotations

from src.services.breach_event_ingest_service import (
    JAPANESE_SCRIPT_RE,
    MONEY_SYMBOL_RE,
    MONEY_WORD_RE,
    NAME_CUE_RE,
)

MANDATORY_DISCLAIMER = (
    "> **AI DRAFT — NOT A FINAL DETERMINATION.** This report was generated by an AI "
    "assistant from anonymized breach data. Contract manager and legal counsel must "
    "verify all facts and review this draft before formal vendor submission.\n\n"
)


def find_prohibited_content_violations(report_text: str) -> list[str]:
    violations: list[str] = []
    name_match = NAME_CUE_RE.search(report_text)
    if name_match:
        violations.append(f"possible employee name detected: '{name_match.group(0)}'")
    money_symbol_match = MONEY_SYMBOL_RE.search(report_text)
    if money_symbol_match:
        violations.append(f"possible monetary value detected: '{money_symbol_match.group(0)}'")
    money_word_match = MONEY_WORD_RE.search(report_text)
    if money_word_match:
        violations.append(f"possible monetary value detected: '{money_word_match.group(0)}'")
    jp_match = JAPANESE_SCRIPT_RE.search(report_text)
    if jp_match:
        violations.append(f"possible Japanese-script identifier detected: '{jp_match.group(0)}'")
    return violations


def attach_disclaimer(report_text: str) -> str:
    return f"{MANDATORY_DISCLAIMER}{report_text}"
